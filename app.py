import os
import streamlit as st
from google import genai

# =====================================================================
# 1. دالة التحليل البلاغي والعروضي الموحد
# =====================================================================
def get_poetry_analysis_prompt(poem_text):
    return f"""
    بصفتك بروفيسور وعالم نقد أدبي ومحقق دواوين وعالم عروض، قم بتحليل القصيدة التالية تحليلاً أكاديمياً موسعاً وشاملاً لكل الأبيات دون أي اختصار أو إيجاز:
    
    القصيدة الكاملة:
    {poem_text}
    
    المطلوب منك في التقرير بدقة وتفصيل:
    1. التحليل العروضي والنمط الإيقاعي: (تحديد بحر القصيدة الخليلي بدقة، التفعيلات العروضية، القافية وحرف الروي، وكتابة التقطيع العروضي الرقمي بالحركات والسكنات 1 و 0 للأبيات).
    2. المدخل الفكري: (شرح السياق العام للقصيدة، الغرض الشعري الرئيسي، والعاطفة المهيمنة).
    3. التحليل التفصيلي والجمعي (بيت ببيت):
       امسك الأبيات بالتتابع، ولكل بيت اذكر:
       - شرح البيت بأسلوب أدبي بليغ ومفصل.
       - علم البيان والبديع (الصور البيانية كالتشبيه والاستعارة والمحسنات كالجناس والطباق والالتفات الخاصة بهذا البيت).
    4. التقييم النقدي العام: (تقييم جودة السبك اللغوي وتماسك القصيدة البنائي).
    
    يرجى كتابة التحليل بلغة عربية فصحى رفيعة وتنسيقه بعناوين ونقاط واضحة جداً ومريحة للقراءة.
    """

# =====================================================================
# 2. واجهة المستخدم الرسومية (RTL)
# =====================================================================
st.set_page_config(page_title="نظام الناقد الذكي الفائق", layout="wide")

st.title("✒️ نظام الناقد الذكي لتحليل وشرح القصائد")
st.write("### فكرة وتطوير المبرمج محمد النِجْري ✨")

with st.sidebar:
    st.header("⚙️ إعدادات النظام")
    st.success("🔒 النظام متصل ومحمي تلقائياً بالسيرفر السحابي الآمن.")
    st.divider()
    st.markdown("### 👨‍💻 مطوّر النظام")
    st.info("تمت البرمجة والتطوير بواسطة: المبرمج محمد النِجْري")

st.subheader("📋 اكتب أو الصق القصيدة الكاملة هنا")
default_poem = "عَلى قَدْرِ أهْلِ العَزْمِ تَأتِي العَزائِمُ\nوَتَأتِي عَلَى قَدْرِ الكِرامِ المَكارِمُ"

poem_input = st.text_area("أدخل أبيات القصيدة (كل بيت في سطر منفصل):", value=default_poem, height=250)

if st.button("🚀 ابدأ التحليل الشامل والعميق للقصيدة بالكامل"):
    st.subheader("🧠 الشرح الأكاديمي والتحليل البلاغي والعروضي المفصل")
    
    # جلب مفتاح التشغيل السري من الخلفية
    api_key = st.secrets.get("GEMINI_API_KEY") or os.environ.get("GEMINI_API_KEY")
    
    if not api_key:
        st.error("⚠️ نظام الحماية السري قيد الإعداد على السيرفر، يرجى وضع المفتاح في لوحة التحكم.")
    else:
        try:
            # تهيئة عميل جوجل
            client = genai.Client(api_key=api_key)
            prompt = get_poetry_analysis_prompt(poem_input)
            
            with st.spinner("جاري قراءة القصيدة وتحليلها..."):
                # استخدام الموديل المستقر والمعتمد دولياً في حزمة المطورين
                response = client.models.generate_content(
                    model='gemini-2.5-flash',
                    contents=prompt,
                )
                st.markdown(response.text)
                
        except Exception as e:
            st.error(f"❌ حدث خطأ أثناء الاتصال بعقل الذكاء الاصطناعي: {str(e)}")

st.divider()
st.write("صُنع بكفاءة برمجية عالية لخدمة لغة الضاد بواسطة المبرمج محمد النِجْري 💻")
