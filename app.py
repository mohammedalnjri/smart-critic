import streamlit as st
import os
from groq import Groq

# 1. إعداد الصفحة والواجهة الاحترافية للموقع
st.set_page_config(
    page_title="Smart Critic - الناقد الذكي",
    page_icon="📚",
    layout="centered"
)

st.title("🤖 منصة الناقد الذكي - Smart Critic")
st.subheader("تحليل ونقد النصوص والمراجع العربية بالذكاء الاصطناعي الأكاديمي")

# 2. جلب المفتاح تلقائياً من إعدادات الـ Secrets
GROQ_API_KEY = os.environ.get("GROQ_API_KEY")

if GROQ_API_KEY:
    # 3. واجهة المراجع والملفات
    st.write("---")
    st.markdown("### 📚 1. المراجع والنصوص المراد تحليلها")
    uploaded_file = st.file_uploader("ارفع الملف أو المرجع العربي (TXT أو PDF):", type=["txt", "pdf"])
    
    context_content = ""
    if uploaded_file is not None:
        try:
            context_content = uploaded_file.read().decode("utf-8", errors="ignore")
            st.success("تم تحميل المرجع بنجاح!")
        except Exception as e:
            st.error(f"خطأ في قراءة الملف: {e}")

    # 4. حقل التوجيهات مع البيت المشكّل كتابةً وصياغةً بشكل صحيح تماماً
    st.write("---")
    st.markdown("### ✍️ 2. توجيهات الناقد الذكي")
    user_prompt = st.text_area(
        "اكتب النص البرومبت (Prompt) أو سؤالك النقدي حول المراجع المرفوعة:",
        value="عَلى قَدْرِ أهْلِ العَزْمِ تَأتِي العَزائِمُ\nوَتَأتِي عَلَى قَدْرِ الكِرامِ المَكارِمُ"
    )

    # 5. معالجة الطلب وعرض النتيجة بشكل صحيح وضبط عروضي صارم
    if st.button("🚀 ابدأ النقد الأدبي والعروضي الموثق"):
        if not user_prompt:
            st.error("الرجاء كتابة التوجيه أو السؤال أولاً!")
        else:
            with st.spinner(""): 
                try:
                    client = Groq(api_key=GROQ_API_KEY)
                    
                    # برومبت أكاديمي صارم يجبر الموديل على الالتزام بقواعد الشعر العربي القديم وعلم العروض
                    full_prompt = f"""
                    أنت بروفيسور خبير ناقد أكاديمي متخصص في النقد الأدبي والشعر العربي القديم وعلم العروض والقافية.
                    
                    تنبيهات صارمة لا تقبل النقاش:
                    1. التزم التزاماً كلياً بقواعد الخليل بن أحمد الفراهيدي وعلم العروض والبحور الشعرية والتفاعيل العربية الأصيلة.
                    2. ممنوع منعاً باتاً استخدام أي مصطلحات غربية أو هجينة مثل "كوبيل" أو "مقطع صوتي غربي".
                    3. تأكد من النسبة التاريخية الصحيحة للشاعر (هذا البيت لأبي الطيب المتنبي من قصيدته الشهيرة في مدح سيف الدولة الحمداني).

                    النص المراد تحليله ونقده: 
                    {user_prompt}

                    المطلوب منك توليد تقرير نقدي فصيح ومفصل ومقسم عبر النقاط التالية بالترتيب:
                    أولاً: توثيق النص ونبذة عن الشاعر والمناسبة التاريخية الصحيحة.
                    ثانياً: الشرح اللغوي والمعنى العام والدلالي للبيوت.
                    ثالثاً: التحليل العروضي والموسيقى الخارجية (حدد البحر الشعري بدقة وهو بحر الطويل، والتفاعيل المقابلة الأصيلة وهي: فعولن مفاعيلن فعولن مفاعيلن في كل شطر، وتعيين الحشو والعروض والضرب بدقة وعلمية).
                    رابعاً: التحليل البلاغي والجمالي (المجاز، التشبيه، الكناية، المحسنات البديعية كالطباق وجناس الاشتقاق بين العزم والعزائم، والكرام والمكارم).
                    """
                    
                    # الموديل المعتمد والمتاح مجاناً والفعال حالياً
                    chat_completion = client.chat.completions.create(
                        messages=[
                            {
                                "role": "user",
                                "content": full_prompt,
                            }
                        ],
                        model="llama-3.1-8b-instant",
                    )
                    
                    # التعديل الصحيح والمضمون لقراءة النص مباشرة بدون أخطاء السقوط السابقة
                    st.write("---")
                    st.markdown("### ✨ النتيجة والنقد الأكاديمي المستخرج:")
                    st.write(chat_completion.choices[0].message.content)
                    
                except Exception as e:
                    st.error(f"⚠️ حدث خطأ أثناء المعالجة: {e}")
else:
    st.info("💡 يرجى التأكد من وضع متغير GROQ_API_KEY داخل منطقة الـ Secrets في إعدادات التطبيق.")
