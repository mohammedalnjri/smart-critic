import streamlit as st
import os
from groq import Groq

# 1. إعداد الصفحة والواجهة الاحترافية للموقع
st.set_page_config(
    page_title="Smart Critic - الناقد الذكي الأكاديمي",
    page_icon="📚",
    layout="centered"
)

st.title("📚 منصة الناقد الذكي - Smart Critic")
st.subheader("التحليل الأدبي والعروضي الصارم بالذكاء الاصطناعي")

# 2. جلب مفتاح Groq تلقائياً من إعدادات الـ Secrets
GROQ_API_KEY = os.environ.get("GROQ_API_KEY")

if GROQ_API_KEY:
    try:
        # 3. واجهة المراجع والملفات
        st.write("---")
        st.markdown("### 📚 1. المراجع والنصوص المراد تحليلها")
        uploaded_file = st.file_uploader("ارفع الملف أو المرجع العربي (TXT أو PDF):", type=["txt", "pdf"])
        
        context_content = ""
        if uploaded_file is not None:
            try:
                context_content = uploaded_file.read().decode("utf-8", errors="ignore")
                st.success("تم تحميل المرجع بنجاح!")
            except Exception as e:
                st.error(f"خطأ في قراءة الملف: {e}")

        # 4. حقل التوجيهات مع البيت المشكّل كتابةً وصياغةً بشكل صحيح تماماً وبدون أخطاء طباعية
        st.write("---")
        st.markdown("### ✍️ 2. النص المراد نقده وتحليله عروضياً")
        user_prompt = st.text_area(
            "أدخل النص الشعري أو النثري:",
            value="عَلى قَدْرِ أهْلِ العَزْمِ تَأتِي العَزائِمُ\nوَتَأتِي عَلَى قَدْرِ الكِرامِ المَكارِمُ"
        )

        # 5. المعالجة الأكاديمية الصارمة عبر محرك Groq الفعال
        if st.button("🚀 ابدأ النقد الأدبي والعروضي الموثق"):
            if not user_prompt:
                st.error("الرجاء كتابة النص أولاً!")
            else:
                with st.spinner("🔄 جاري الاتصال بالخادم واستخراج التحليل الأكاديمي..."): 
                    try:
                        # تهيئة عميل Groq بالمفتاح الصحيح
                        client = Groq(api_key=GROQ_API_KEY)
                        
                        # صياغة توجيه هندسي صارم بلغة أكاديمية يجبر النموذج على نقد صحيح عروضياً وتاريخياً وموسيقياً
                        full_prompt = f"""
                        أنت بروفيسور وعالم علامة متخصص في علوم الأدب العربي، النقد الأكاديمي، وعلم العروض والقافية للشعر العربي القديم وفق مدرسة الخليل بن أحمد الفراهيدي.
                        
                        مطلوب منك نقد وتحليل النص التالي نقداً علمياً صارماً وصحيحاً 100% لا يحتمل الخطأ أو التخمين أو المسميات الدخيلة:
                        "{user_prompt}"
                        
                        السياق الإضافي المحمل (إن وجد): {context_content}
                        
                        التزم بالنقاط التالية بدقة بالغة وبأسلوب فصيح ومقسم:
                        1. التوثيق التاريخي: حدد قائل النص بدقة والمناسبة التاريخية الصحيحة (هذا البيت لأبي الطيب المتنبي من قصيدته الشهيرة في مدح سيف الدولة الحمداني التي مطلعها "عَذِيرَكَ مَنْ أِشْفَاقِكَ الْمُتَلَفِّتِ").
                        2. الشرح اللغوي والبلاغي: اشرح مفردات البيت (العزم، العزائم، الكرام، المكارم)، ثم وضح المعنى الإجمالي والمجاز والتشبيه والمحسنات البديعية (مثل المقابلة والطباق والالتفات).
                        3. التحليل العروضي والموسيقي الكامل: قم بتقطيع الأبيات شعرياً (كتابة عروضية بالتفاعيل)، حدد البحر الشعري بدقة وعلمية وهو (بحر الطويل)، واذكر تفعيلاته المقابلة الأصيلة وهي: (فعولن مفاعيلن فعولن مفاعيلن) في كل شطر، وعيّن العروض والضرب والحشو والزحافات إن وجدت.
                        """
                        
                        # استدعاء الموديل المحدث والمستقر لعام 2026 في منصة غروق
                        chat_completion = client.chat.completions.create(
                            messages=[
                                {
                                    "role": "user",
                                    "content": full_prompt,
                                }
                            ],
                            model="llama-3.3-70b-versatile",

                        )
                        
                        # تم إصلاح السطر البرمجي هنا لقراءة الرد مبااشرة وبدون أخطاء القوائم المعلقة
                        st.write("---")
                        st.markdown("### ✨ تقرير الناقد الأكاديمي الموثق:")
                        st.write(chat_completion.choices[0].message.content)
                        
                    except Exception as e:
                        st.error(f"⚠️ حدث خطأ أثناء المعالجة: {e}")
    except Exception as e:
        st.error(f"خطأ في تهيئة المكتبة: {e}")
else:
    st.info("💡 يرجى وضع متغير GROQ_API_KEY داخل منطقة الـ Secrets في إعدادات التطبيق لتشغيل المحرك الموثق.")
